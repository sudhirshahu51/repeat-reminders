def rrect(x, y, w, h, r):
    return (f"M{x + r},{y} h{w - 2 * r} a{r},{r} 0 0 1 {r},{r} v{h - 2 * r} a{r},{r} 0 0 1 {-r},{r} "
            f"h{-(w - 2 * r)} a{r},{r} 0 0 1 {-r},{-r} v{-(h - 2 * r)} a{r},{r} 0 0 1 {r},{-r} z")


def circle(cx, cy, r):
    return f"M{cx},{cy - r} a{r},{r} 0 1 1 0,{2 * r} a{r},{r} 0 1 1 0,{-2 * r} z"


def bell_path(x, y, u):
    """Bell with a flared rim, knob and clapper; (x, y) is the middle of the rim's bottom edge."""
    def p(dx, dy):
        return f"{x + dx * u:.2f},{y + dy * u:.2f}"
    body = (f"M{p(-9, 0)} L{p(-9, -1.6)} C{p(-9, -3)} {p(-6.5, -3)} {p(-6.5, -5)} L{p(-6.5, -8)} "
            f"C{p(-6.5, -12.5)} {p(-3.8, -15)} {p(0, -15)} C{p(3.8, -15)} {p(6.5, -12.5)} {p(6.5, -8)} "
            f"L{p(6.5, -5)} C{p(6.5, -3)} {p(9, -3)} {p(9, -1.6)} L{p(9, 0)} Z")
    r = 1.7 * u
    knob = f"M{p(0, -15.2 - 1.7)} a{r:.2f},{r:.2f} 0 1 1 0,{2 * r:.2f} a{r:.2f},{r:.2f} 0 1 1 0,{-2 * r:.2f} Z"
    c = 2.7 * u
    clapper = f"M{p(-2.7, 0)} a{c:.2f},{c:.2f} 0 0 0 {2 * c:.2f},0 Z"
    return f"{body} {knob} {clapper}"


def background(colours):
    """(kind, d, style) for the full-bleed gradient behind the notebook."""
    return [("grad", "M0,0 h108 v108 h-108 z", (colours[0], colours[1], 0, 0, 108, 108))]


def mix(c, other, t):
    a = [int(c[i:i + 2], 16) for i in (1, 3, 5)]
    b = [int(other[i:i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join(f"{round(x + (y - x) * t):02X}" for x, y in zip(a, b))


# The artwork is laid out in the coordinates of the 1024 px reference picture (page, three dots, lines, bell) and scaled
# into the 108 space: IMG_K sets the size, and the middle of the picture lands on (54, 54).
IMG_K = 0.068
IMG_CX, IMG_CY = 521.5, 522.5
BELL_LIGHT, BELL_DARK = "#FAC328", "#E9B20D"


def _t(x, y):
    return 54 + (x - IMG_CX) * IMG_K, 54 + (y - IMG_CY) * IMG_K


def _pt(x, y):
    X, Y = _t(x, y)
    return f"{X:.2f},{Y:.2f}"


def img_rrect(x1, y1, x2, y2, r):
    k = r * IMG_K
    a = f"A{k:.2f},{k:.2f} 0 0 1 "
    return (f"M{_pt(x1 + r, y1)} L{_pt(x2 - r, y1)} {a}{_pt(x2, y1 + r)} L{_pt(x2, y2 - r)} {a}{_pt(x2 - r, y2)} "
            f"L{_pt(x1 + r, y2)} {a}{_pt(x1, y2 - r)} L{_pt(x1, y1 + r)} {a}{_pt(x1 + r, y1)} Z")


def img_circle(cx, cy, r):
    k = r * IMG_K
    return (f"M{_pt(cx - r, cy)} A{k:.2f},{k:.2f} 0 1 1 {_pt(cx + r, cy)} A{k:.2f},{k:.2f} 0 1 1 {_pt(cx - r, cy)} Z")


def img_bell():
    """Flat two-tone bell (left half lighter), as in the reference picture; returns [(kind, d, style)]."""
    p = _pt
    k = lambda r: f"{r * IMG_K:.2f}"
    clapper_l = f"M{p(693, 877)} H{_t(748, 0)[0]:.2f} V{_t(0, 932)[1]:.2f} A{k(55)},{k(55)} 0 0 1 {p(693, 877)} Z"
    clapper_r = f"M{p(748, 877)} H{_t(803, 0)[0]:.2f} A{k(55)},{k(55)} 0 0 1 {p(748, 932)} Z"
    left = (f"M{p(585, 865)} L{p(585, 835)} C{p(585, 812)} {p(625, 805)} {p(625, 760)} L{p(625, 705)} "
            f"C{p(625, 640)} {p(680, 607)} {p(748, 607)} C{p(816, 607)} {p(868, 640)} {p(868, 705)} "
            f"L{p(868, 760)} C{p(868, 805)} {p(910, 812)} {p(910, 835)} L{p(910, 865)} "
            f"Q{p(910, 877)} {p(898, 877)} L{p(597, 877)} Q{p(585, 877)} {p(585, 865)} Z")
    right = (f"M{p(748, 607)} C{p(816, 607)} {p(868, 640)} {p(868, 705)} L{p(868, 760)} "
             f"C{p(868, 805)} {p(910, 812)} {p(910, 835)} L{p(910, 865)} Q{p(910, 877)} {p(898, 877)} L{p(748, 877)} Z")
    knob_l = img_circle(748, 600, 34)
    knob_r = f"M{p(748, 566)} A{k(34)},{k(34)} 0 0 1 {p(748, 634)} Z"
    return [("fill", clapper_l, BELL_LIGHT), ("fill", clapper_r, BELL_DARK),
            ("fill", knob_l, BELL_LIGHT), ("fill", knob_r, BELL_DARK),
            ("fill", left, BELL_LIGHT), ("fill", right, BELL_DARK)]


def foreground(page=None, night=False):
    """List of (kind, d, style). kind: fill | grad | stroke. [page] is the page colour; None is white."""
    out = []
    face = img_rrect(133, 105, 812, 885, 75)
    shadow = img_rrect(133, 135, 812, 915, 75)  # the page's thickness, showing below it
    if page is None:
        out.append(("fill", shadow, "#E3E3E3"))
        if night:
            out.append(("stroke", shadow, (1.0, NIGHT_PAGE_EDGE)))
        out.append(("fill", face, "#FFFFFF"))
        dots, line = ROWS, LINE
    else:
        # coloured page with a white edge, so it still stands out on a background of the same colour
        out.append(("fill", shadow, mix(page, "#000000", 0.3)))
        gx, g0 = _t(0, 105)[0], _t(0, 105)[1]
        out.append(("grad", face, (mix(page, "#FFFFFF", 0.12), mix(page, "#000000", 0.15), gx, g0, gx, _t(0, 885)[1])))
        out.append(("stroke", face, (1.4, "#FFFFFF")))
        dots, line = ["#FFFFFF"] * 3, mix(page, "#FFFFFF", 0.6)
    for i, c in enumerate(dots):
        cy = 285 + 210 * i
        out.append(("fill", img_circle(302, cy, 83), c))
        # a line is a round-capped stroke, so it starts and ends one cap radius inside the 415..732 span
        out.append(("stroke", f"M{_pt(433, cy)} H{_t(714, 0)[0]:.2f}", (36 * IMG_K, line)))
    out.extend(img_bell())
    return out


def vector_xml(shapes, comment):
    parts = []
    for kind, d, style in shapes:
        if kind == "fill":
            parts.append(f'    <path android:fillColor="{style}" android:pathData="{d}" />')
        elif kind == "grad":
            c0, c1, x0, y0, x1, y1 = style
            parts.append(
                f'    <path android:pathData="{d}">\n'
                f'        <aapt:attr name="android:fillColor">\n'
                f'            <gradient android:type="linear" android:startX="{x0}" android:startY="{y0}" '
                f'android:endX="{x1}" android:endY="{y1}" android:startColor="{c0}" android:endColor="{c1}" />\n'
                f'        </aapt:attr>\n'
                f'    </path>'
            )
        elif kind == "badge":
            fill, edge = style
            parts.append(f'    <path android:fillColor="#FFFFFF" android:strokeColor="#FFFFFF" android:strokeWidth="3.6" '
                         f'android:strokeLineJoin="round" android:pathData="{d}" />')
            parts.append(f'    <path android:fillColor="{fill}" android:strokeColor="{edge}" android:strokeWidth="1.2" '
                         f'android:strokeLineJoin="round" android:pathData="{d}" />')
        else:
            width, colour = style
            parts.append(f'    <path android:strokeColor="{colour}" android:strokeWidth="{width}" '
                         f'android:strokeLineCap="round" android:pathData="{d}" />')
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            f'<!-- Generated by store/make_launcher_icons.py: {comment} -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    xmlns:aapt="http://schemas.android.com/aapt"\n'
            '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
            + "\n".join(parts) + "\n</vector>\n")


def notebook_glyph():
    """One-colour version of the icon in a 24 x 24 box: a page with three to-do rows cut out, and the bell sitting
    in a round hole at the bottom right. Drawn even-odd, so every nested shape flips between filled and empty."""
    page = rrect(2.5, 1, 17, 22, 2.4)
    hole = circle(14, 17.2, 5.0)  # around the bell
    rows = []
    for i, y in enumerate((5, 9.5, 14)):
        rows.append(circle(5.8, y, 1.7))  # bullet ring (hole) ...
        rows.append(circle(5.8, y, 0.75))  # ... with a filled dot
        if i < 2:  # the bell's hole leaves no room for the last row's line
            rows.append(rrect(8.6, y - 0.7, 16.8 - 8.6, 1.4, 0.7))
    notebook = " ".join([page, hole] + rows)
    bell = bell_path(14, 17.2 + 8 * 0.36, 0.36)
    return notebook, bell


def glyph_xml(size, scale, offset, comment):
    group = f'android:translateX="{offset}" android:translateY="{offset}" android:scaleX="{scale}" android:scaleY="{scale}"'
    notebook, bell = notebook_glyph()
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            f'<!-- Generated by store/make_launcher_icons.py: {comment} -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{size}dp" android:height="{size}dp" android:viewportWidth="{size}" android:viewportHeight="{size}">\n'
            f'    <group {group}>\n'
            f'        <path android:fillColor="#FFFFFFFF" android:fillType="evenOdd" android:pathData="{notebook}" />\n'
            f'        <path android:fillColor="#FFFFFFFF" android:pathData="{bell}" />\n'
            '    </group>\n'
            '</vector>\n')


def mipmap_name(bg, nb):
    """ic_launcher (black, white page), ic_launcher_teal (teal, white page), ic_launcher_default_green, ..."""
    if not nb:
        return "ic_launcher" if bg == "default" else f"ic_launcher_{bg}"
    return f"ic_launcher_{bg}_{nb}"


def alias_name(bg, nb):
    """Matches AppIcons.kt: AppIcon.alias + Accent.notebook, e.g. LauncherDefault, LauncherDefaultGreen."""
    return "Launcher" + bg.capitalize() + nb.capitalize()


def write_manifest_aliases():
    path = ROOT / "app/src/main/AndroidManifest.xml"
    text = path.read_bytes().decode("utf-8").replace("\r\n", "\n")
    start, end = "<!-- launcher-aliases:start -->", "<!-- launcher-aliases:end -->"
    head, rest = text.split(start)
    _, tail = rest.split(end)
    blocks = []
    for bg in COLOURS:
        for nb in NOTEBOOKS:
            icon = mipmap_name(bg, nb)
            enabled = "true" if bg == "default" and not nb else "false"
            blocks.append(
                '        <activity-alias\n'
                f'            android:name=".{alias_name(bg, nb)}"\n'
                f'            android:enabled="{enabled}"\n'
                '            android:exported="true"\n'
                f'            android:icon="@mipmap/{icon}"\n'
                f'            android:roundIcon="@mipmap/{icon}"\n'
                '            android:targetActivity=".ui.MainActivity">\n'
                '            <intent-filter>\n'
                '                <action android:name="android.intent.action.MAIN" />\n'
                '                <category android:name="android.intent.category.LAUNCHER" />\n'
                '            </intent-filter>\n'
                '        </activity-alias>\n')
    text = head + start + "\n" + "".join(blocks) + "        " + end + tail
    path.write_bytes(text.replace("\n", "\r\n").encode("utf-8"))


def write_resources():
    draw = RES / "drawable"
    mip = RES / "mipmap-anydpi-v26"
    for old in [*draw.glob("ic_launcher_fg*.xml"), *draw.glob("ic_launcher_bg_*.xml"), *mip.glob("ic_launcher*.xml")]:
        old.unlink()
    fg = {nb: f"ic_launcher_fg_{nb}" if nb else "ic_launcher_fg" for nb in NOTEBOOKS}
    for nb, page in NOTEBOOKS.items():
        (draw / f"{fg[nb]}.xml").write_text(
            vector_xml(foreground(page), f"{nb or 'white'} notebook with to-do rows and a reminder bell."), encoding="utf-8")
    for name, colours in COLOURS.items():
        (draw / f"ic_launcher_bg_{name}.xml").write_text(vector_xml(background(colours), f"{name} icon background."), encoding="utf-8")
        for nb in NOTEBOOKS:
            (mip / f"{mipmap_name(name, nb)}.xml").write_text(
                '<?xml version="1.0" encoding="utf-8"?>\n'
                '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
                f'    <background android:drawable="@drawable/ic_launcher_bg_{name}" />\n'
                f'    <foreground android:drawable="@drawable/{fg[nb]}" />\n'
                '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
                '</adaptive-icon>\n', encoding="utf-8")
    write_manifest_aliases()
    # Dark mode: white default background; the white page needs an edge to show on it.
    night = RES / "drawable-night"
    night.mkdir(exist_ok=True)
    for old in night.glob("ic_launcher_*.xml"):
        old.unlink()
    (night / "ic_launcher_bg_default.xml").write_text(
        vector_xml(background(NIGHT_DEFAULT), "default icon background in dark mode."), encoding="utf-8")
    (night / "ic_launcher_fg.xml").write_text(
        vector_xml(foreground(None, night=True), "white notebook (with an edge) in dark mode."), encoding="utf-8")
    (draw / "ic_launcher_monochrome.xml").write_text(
        glyph_xml(108, 2, 30, "themed-icon layer (Android 13+), tinted by the system."), encoding="utf-8")
    (draw / "ic_stat_alarm.xml").write_text(STAT_BELL, encoding="utf-8")
    # The icon's yellow bell on its own, for reminders without an emoji in the app.
    bell = bell_path(12, 21, 1.0)
    (draw / "ic_bell_badge.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by store/make_launcher_icons.py: the app icon's reminder bell. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n'
        f'    <path android:fillColor="{BELL_FILL}" android:strokeColor="{BELL_EDGE}" android:strokeWidth="1.2" '
        f'android:strokeLineJoin="round" android:pathData="{bell}" />\n'
        '</vector>\n', encoding="utf-8")


def render_png(path, colours, px, view=(14, 14, 94, 94), with_background=True, page=None, night=False):
    """Renders the icon (real gradients) to a px x px PNG covering [view] of the 108 space."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import numpy as np
    from matplotlib.colors import to_rgb
    from matplotlib.patches import PathPatch
    from svgpath2mpl import parse_path

    x0, y0, x1, y1 = view
    fig = plt.figure(figsize=(1, 1), dpi=px)
    ax = fig.add_axes([0, 0, 1, 1])
    ax.set_xlim(x0, x1); ax.set_ylim(y1, y0); ax.axis("off")
    pts_per_unit = 72 / (x1 - x0)
    shapes = (background(colours) if with_background else []) + foreground(page, night)
    n = 400
    gx, gy = np.meshgrid(np.linspace(x0, x1, n), np.linspace(y0, y1, n))
    for kind, d, style in shapes:
        p = parse_path(d)
        if kind == "fill":
            ax.add_patch(PathPatch(p, facecolor=style, lw=0))
        elif kind == "grad":
            c0, c1, sx, sy, ex, ey = style
            patch = PathPatch(p, facecolor="none", lw=0)
            ax.add_patch(patch)
            dx, dy = ex - sx, ey - sy
            t = np.clip(((gx - sx) * dx + (gy - sy) * dy) / (dx * dx + dy * dy), 0, 1)[..., None]
            a, b = np.array(to_rgb(c0)), np.array(to_rgb(c1))
            im = ax.imshow(a + (b - a) * t, extent=[x0, x1, y1, y0], interpolation="bilinear")
            im.set_clip_path(patch)
        elif kind == "badge":
            ax.add_patch(PathPatch(p, facecolor="white", edgecolor="white", lw=3.6 * pts_per_unit, joinstyle="round"))
            ax.add_patch(PathPatch(p, facecolor=style[0], edgecolor=style[1], lw=1.2 * pts_per_unit, joinstyle="round"))
        else:
            width, colour = style
            ax.add_patch(PathPatch(p, facecolor="none", edgecolor=colour, lw=width * pts_per_unit, capstyle="round"))
    ax.set_xlim(x0, x1); ax.set_ylim(y1, y0)
    fig.savefig(path, dpi=px, transparent=not with_background)
    plt.close(fig)


def preview(path):
    """Every notebook colour on black (light mode) and on white (dark mode), then every background with the white page, cut to the circle a Pixel
    launcher shows (72dp of the 108dp icon)."""
    import tempfile
    from PIL import Image, ImageDraw

    size = 220
    rows = [[(COLOURS["default"], page, False) for page in NOTEBOOKS.values()],
            [(NIGHT_DEFAULT, page, True) for page in NOTEBOOKS.values()],
            [(c, None, False) for c in COLOURS.values()]]
    cols = max(len(r) for r in rows)
    strip = Image.new("RGB", (size * cols + 20 * (cols + 1), (size + 20) * len(rows) + 20), (207, 207, 207))
    mask = Image.new("L", (size, size), 0)
    ImageDraw.Draw(mask).ellipse([0, 0, size - 1, size - 1], fill=255)
    with tempfile.TemporaryDirectory() as tmp:
        for j, row in enumerate(rows):
            for i, (colours, page, night) in enumerate(row):
                f = Path(tmp) / f"{j}_{i}.png"
                render_png(f, colours, size, view=(18, 18, 90, 90), page=page, night=night)
                strip.paste(Image.open(f).convert("RGB"), (20 + i * (size + 20), 20 + j * (size + 20)), mask)
    strip.save(path)


if __name__ == "__main__":
    import sys
    write_resources()
    if len(sys.argv) > 1:
        preview(sys.argv[1])
    print("ok")
